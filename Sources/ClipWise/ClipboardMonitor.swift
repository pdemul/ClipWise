import AppKit

/// macOS has no clipboard-change notification, so poll changeCount.
@MainActor
final class ClipboardMonitor {
    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    private let onCopy: (String) -> Void

    // Set by password managers and the like; see nspasteboard.org.
    private static let skipTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    init(onCopy: @escaping (String) -> Void) {
        self.onCopy = onCopy
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    /// Put text on the clipboard without recording it as a new copy.
    func write(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastChangeCount = pasteboard.changeCount
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        if let types = pasteboard.types, !Self.skipTypes.isDisjoint(with: types) { return }
        guard let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        onCopy(text)

        // A transform adds its result as a second, newer entry and puts it on the clipboard.
        // Only real copies get here, so picking an old "4127*123" from the menu re-copies the sum as is.
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        Task {
            guard let result = await applyTransformers(trimmed) else { return }
            // A lookup can take a moment; never overwrite something copied in the meantime.
            guard pasteboard.changeCount == count else {
                NSLog("ClipWise: dropped transform result for \"\(trimmed.prefix(40))\", clipboard changed meanwhile")
                return
            }
            write(result)
            onCopy(result)
        }
    }
}
